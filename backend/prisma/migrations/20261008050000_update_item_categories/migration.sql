-- AlterEnum
BEGIN;
CREATE TYPE "ItemCategory_new" AS ENUM ('FURNITURE', 'LIGHTING', 'WALL_DECOR', 'FLOOR_AND_TEXTILES', 'PLANTS_AND_NATURE', 'DECORATIVE_OBJECTS', 'ELECTRONICS', 'STORAGE_AND_ORGANIZATION', 'OTHER');
ALTER TABLE "Item" ALTER COLUMN "category" TYPE "ItemCategory_new" USING (
  CASE "category"::text
    WHEN 'SOFA' THEN 'FURNITURE'
    WHEN 'COFFEE_TABLE' THEN 'FURNITURE'
    WHEN 'CHAIR' THEN 'FURNITURE'
    WHEN 'RUG' THEN 'FLOOR_AND_TEXTILES'
    WHEN 'LAMP' THEN 'LIGHTING'
    WHEN 'PLANT' THEN 'PLANTS_AND_NATURE'
    WHEN 'SHELF' THEN 'STORAGE_AND_ORGANIZATION'
    ELSE 'OTHER'
  END
)::"ItemCategory_new";
ALTER TYPE "ItemCategory" RENAME TO "ItemCategory_old";
ALTER TYPE "ItemCategory_new" RENAME TO "ItemCategory";
DROP TYPE "public"."ItemCategory_old";
COMMIT;
